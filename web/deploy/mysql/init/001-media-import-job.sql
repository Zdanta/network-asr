CREATE TABLE IF NOT EXISTS media_import_job (
  id BIGINT NOT NULL AUTO_INCREMENT,
  job_id VARCHAR(64) NOT NULL,
  user_id BIGINT NOT NULL,
  source_text TEXT NOT NULL,
  source_url VARCHAR(1000) NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'INIT',
  progress INT NOT NULL DEFAULT 0,
  stage VARCHAR(64) NULL,
  file_id BIGINT NULL,
  task_no VARCHAR(64) NULL,
  title VARCHAR(255) NULL,
  download_engine VARCHAR(64) NULL,
  cookie_source VARCHAR(128) NULL,
  error_message VARCHAR(1000) NULL,
  deleted INT NOT NULL DEFAULT 0,
  created_by BIGINT NULL,
  updated_by BIGINT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uk_media_import_job_job_id (job_id),
  KEY idx_media_import_job_user_id (user_id),
  KEY idx_media_import_job_status (status),
  KEY idx_media_import_job_task_no (task_no),
  KEY idx_media_import_job_created_at (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Media link import async jobs';
