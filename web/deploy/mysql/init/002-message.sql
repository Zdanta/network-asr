CREATE TABLE IF NOT EXISTS message (
  id BIGINT NOT NULL AUTO_INCREMENT,
  user_id BIGINT NOT NULL,
  message_type VARCHAR(32) NOT NULL,
  title VARCHAR(128) NOT NULL,
  content VARCHAR(1000) NOT NULL,
  biz_type VARCHAR(32) NULL,
  biz_no VARCHAR(128) NULL,
  action_text VARCHAR(64) NULL,
  action_url VARCHAR(255) NULL,
  read_status VARCHAR(20) NOT NULL DEFAULT 'UNREAD',
  read_at DATETIME NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'ENABLE',
  deleted INT NOT NULL DEFAULT 0,
  created_by BIGINT NULL,
  updated_by BIGINT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_message_user_id (user_id),
  KEY idx_message_type (message_type),
  KEY idx_message_read_status (read_status),
  KEY idx_message_biz_no (biz_no),
  KEY idx_message_created_at (created_at),
  KEY idx_message_user_read_created (user_id, read_status, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='User messages';
